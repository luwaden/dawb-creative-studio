/**
 * Builds src/lib/geo/maps.ts — pre-projected SVG paths for the chart "map" type.
 * Source: Natural Earth (public domain) — admin-1 states (Nigeria) and 1:50m countries (Africa).
 * Paths are projected and simplified once here, so the app ships no GIS libraries.
 *   npm run maps:build
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { geoArea, geoMercator, geoPath } from "d3-geo";

const BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/";
const cache = join(tmpdir(), "dawb-maps");
mkdirSync(cache, { recursive: true });

async function load(name) {
  const file = join(cache, name);
  if (!existsSync(file)) {
    console.log(`Downloading ${name}…`);
    const res = await fetch(BASE + name);
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
    writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return JSON.parse(readFileSync(file, "utf8"));
}

/** Closed ring: split at the point farthest from the start so neither half is degenerate. */
function simplifyRing(ring, tol) {
  const pts = ring.slice(0, -1);
  if (pts.length < 4) return pts;
  let far = 0, fd = -1;
  pts.forEach(([x, y], i) => { const d = (x - pts[0][0]) ** 2 + (y - pts[0][1]) ** 2; if (d > fd) { fd = d; far = i; } });
  const a = simplify(pts.slice(0, far + 1), tol);
  const b = simplify([...pts.slice(far), pts[0]], tol);
  return [...a, ...b.slice(1, -1)];
}

/** Douglas–Peucker on a projected polyline. */
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

/** Natural Earth rings are counter-clockwise (RFC 7946); d3-geo wants clockwise exteriors. */
function rewind(f) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const fixed = polys.map((poly) => (geoArea({ type: "Polygon", coordinates: poly }) > 2 * Math.PI ? poly.map((r) => [...r].reverse()) : poly));
  return { ...f, geometry: { type: "MultiPolygon", coordinates: fixed } };
}

function build(raw, { width, idOf, nameOf, tol = 0.7, minArea = 6 }) {
  const features = raw.map(rewind);
  const fc = { type: "FeatureCollection", features };
  const projection = geoMercator().fitWidth(width, fc);
  const path = geoPath(projection);
  const [[, y0], [, y1]] = path.bounds(fc);
  const height = Math.ceil(y1 - y0 + 4);
  projection.translate([projection.translate()[0], projection.translate()[1] - y0 + 2]);
  const regions = features.map((f) => {
    const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
    let d = "";
    for (const poly of polys) {
      for (const ring of poly) {
        const pts = simplifyRing(ring.map((c) => projection(c)).filter(Boolean), tol);
        if (pts.length < 3) continue;
        let area = 0;
        for (let i = 0; i < pts.length; i++) { const [x1, y1_] = pts[i], [x2, y2] = pts[(i + 1) % pts.length]; area += x1 * y2 - x2 * y1_; }
        if (Math.abs(area / 2) < minArea) continue;
        d += "M" + pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join("L") + "Z";
      }
    }
    const [cx, cy] = path.centroid(f);
    return { id: idOf(f), name: nameOf(f), d, cx: Math.round(cx), cy: Math.round(cy) };
  }).filter((r) => r.d);
  regions.sort((a, b) => a.name.localeCompare(b.name));
  return { width, height, regions };
}

const admin1 = await load("ne_10m_admin_1_states_provinces.geojson");
const nigeria = build(admin1.features.filter((f) => f.properties.adm0_a3 === "NGA"), {
  width: 1000,
  idOf: (f) => (f.properties.postal || f.properties.iso_3166_2 || f.properties.name).replace(/^NG-/, ""),
  nameOf: (f) => ({ "Federal Capital Territory": "FCT Abuja", Nassarawa: "Nasarawa" })[f.properties.name] ?? f.properties.name,
});
const admin0 = await load("ne_50m_admin_0_countries.geojson");
const africa = build(admin0.features.filter((f) => f.properties.CONTINENT === "Africa"), {
  width: 1000,
  tol: 0.9,
  minArea: 4,
  idOf: (f) => f.properties.ADM0_A3,
  nameOf: (f) => f.properties.NAME,
});

const out = `/* Generated by scripts/build-maps.mjs from Natural Earth (public domain). Do not edit by hand. */
export interface MapRegion { id: string; name: string; d: string; cx: number; cy: number }
export interface GeoMap { width: number; height: number; regions: MapRegion[] }
export type MapId = "nigeria" | "africa";
export const MAPS: Record<MapId, GeoMap> = ${JSON.stringify({ nigeria, africa })};
`;
writeFileSync("src/lib/geo/maps.ts", out);
console.log(`nigeria: ${nigeria.regions.length} regions, africa: ${africa.regions.length}; ${(out.length / 1024).toFixed(0)} KB`);
