/**
 * Regenerates the font imports from src/lib/fonts.ts so the editor/exports
 * (src/app/fonts.css) and server video renders (src/remotion/fonts.ts) always
 * load exactly the same files. Run after editing FONTS:  npm run fonts:sync
 */
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FONTS, fontPackage } from "../src/lib/fonts";

const root = process.cwd();
const files: string[] = [];
for (const f of FONTS) {
  const pkg = fontPackage(f.family);
  const faces = [...f.weights.map((w) => `latin-${w}.css`), ...(f.italics ?? []).map((w) => `latin-${w}-italic.css`)];
  for (const face of faces) {
    const path = `@fontsource/${pkg}/${face}`;
    if (!existsSync(join(root, "node_modules", path))) throw new Error(`Missing ${path} — run: npm i @fontsource/${pkg}`);
    files.push(path);
  }
}
const banner = "Generated by scripts/sync-fonts.ts from src/lib/fonts.ts — do not edit by hand.";
writeFileSync(join(root, "src/app/fonts.css"), `/* ${banner} */\n${files.map((p) => `@import "${p}";`).join("\n")}\n`);
writeFileSync(join(root, "src/remotion/fonts.ts"), `/* Fonts for server-side renders. ${banner} */\n${files.map((p) => `import "${p}";`).join("\n")}\n`);
console.log(`${FONTS.length} families, ${files.length} font faces written.`);
